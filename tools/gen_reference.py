#!/usr/bin/env python3
"""Generate the three reference pages in 09_reference/ from an Airflow source checkout.

Usage:
  python3 tools/gen_reference.py <airflow-checkout> [--only config|cli|metrics]

Writes:
  09_reference/01_airflow_cfg_reference.md   every [section] key in config.yml, with default and env var
  09_reference/02_cli_reference.md           every core `airflow` CLI command and argument (cli_config.py)
  09_reference/03_metrics_reference.md       every metric in the metrics registry

Use the branch the guide describes (v3-4-stable). A tarball or `git archive` export works too; set
AIRFLOW_SOURCE_COMMIT to record the commit when the checkout has no .git directory.
Needs Python 3.10+ and PyYAML.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import airflow_source as src  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAUTION = (
    "> [!CAUTION]\n"
    "> Commands and settings on this page can change or delete data and affect running deployments. "
    "Try them on a test or staging deployment first, and read the [disclaimer](../README.md#disclaimer). "
    'The guide is provided "as is", without warranty.\n'
)


def header(title: str, source: str, origin: str, intro: str) -> str:
    return (
        f"# {title}\n\n{CAUTION}\n"
        f"<!-- Generated by tools/gen_reference.py from Apache Airflow {origin}. Do not edit by hand. -->\n\n"
        f"> **Generated page.** Built from [`{source}`](https://github.com/apache/airflow/blob/v3-4-stable/{source}) "
        f"in Apache Airflow {origin}. Descriptions are taken from the Airflow source (Apache-2.0) and may be "
        "shortened or reformatted. Regenerate with `tools/gen_reference.py`; see [tools/README.md](../tools/README.md).\n\n"
        f"{intro}\n"
    )


def rst_to_md(text: str) -> str:
    """Convert the small subset of reStructuredText used in Airflow help strings to Markdown."""
    if not text:
        return ""
    text = text.replace("\r", "")
    lines, out, i = text.split("\n"), [], 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^(\s*)\.\. code-block::\s*(\w*)", line)
        if m:
            lang, base = m.group(2), len(m.group(1))
            i += 1
            block = []
            while i < len(lines) and (not lines[i].strip() or len(lines[i]) - len(lines[i].lstrip()) > base):
                block.append(lines[i])
                i += 1
            while block and not block[-1].strip():
                block.pop()
            while block and not block[0].strip():
                block.pop(0)
            indent = min((len(b) - len(b.lstrip()) for b in block if b.strip()), default=0)
            out += [f"```{lang}"] + [b[indent:] for b in block] + ["```"]
            continue
        if re.match(r"^\s*\.\. (note|warning|seealso|versionadded|versionchanged)::", line):
            line = re.sub(r"^\s*\.\. (\w+)::\s*", lambda mm: f"**{mm.group(1).capitalize()}:** ", line)
        line = re.sub(r"`([^`<]+?)\s*<(https?://[^>]+)>`_{1,2}", r"[\1](\2)", line)
        line = re.sub(r":\w+:`([^`]+)`", r"`\1`", line)
        line = re.sub(r"``([^`]+)``", r"`\1`", line)
        out.append(line)
        i += 1
    return "\n".join(out).strip()


def cell(text: str | None) -> str:
    if text is None or text == "":
        return ""
    return str(text).replace("|", "\\|").replace("\n", " ")


def code_cell(value) -> str:
    if value is None:
        return "*(none)*"
    s = str(value)
    if s == "":
        return "*(empty)*"
    s = s.replace("\n", " ").replace("|", "\\|")
    return f"`{s}`" if "`" not in s else f"``{s}``"


# --- config --------------------------------------------------------------------------------


def gen_config(checkout: str, origin: str) -> str:
    cfg = src.load_config(checkout)
    deprecated = src.load_deprecated_options(checkout)
    count = sum(len(s.get("options") or {}) for s in cfg.values())
    intro = (
        f"Every key in Airflow's core configuration: {len(cfg)} sections, {count} keys. Set a key in "
        "`airflow.cfg`, or with the environment variable `AIRFLOW__<SECTION>__<KEY>` (upper case, double "
        "underscores), which wins over the file. Keys marked **sensitive** also accept `AIRFLOW__<SECTION>__<KEY>_CMD` "
        "and `_SECRET`; see [Configuration and Tuning](../05_deployment_and_config/01_configuration_and_tuning.md).\n\n"
        "Provider sections (`[celery]`, `[kubernetes_executor]`, `[fab]`, `[smtp_provider]` and others) are defined "
        "by each provider's `provider.yaml` and are not listed here. Defaults are as written in `config.yml`: "
        "`{AIRFLOW_HOME}` is expanded at run time, and an empty default means unset."
    )
    parts = [header("airflow.cfg Reference", src.CONFIG_YML, origin, intro)]

    parts.append("## Sections\n")
    parts.append("| Section | Keys | Description |\n| :--- | ---: | :--- |")
    for name, sec in cfg.items():
        first = rst_to_md(sec.get("description") or "").split("\n")[0]
        parts.append(f"| [`[{name}]`](#{name.replace('_', '_')}) | {len(sec.get('options') or {})} | {cell(first)} |")
    parts.append("")

    if deprecated:
        parts.append("## Renamed keys\n")
        parts.append(
            "Old names still work, with a deprecation warning, until a later major release. Use the new name in "
            "new configuration.\n"
        )
        parts.append("| Old key | New key | Renamed in |\n| :--- | :--- | :--- |")
        for (new_s, new_k), (old_s, old_k, ver) in sorted(deprecated.items(), key=lambda x: (x[1][0], x[1][1])):
            if new_k in ((cfg.get(new_s) or {}).get("options") or {}):
                new = f"[`[{new_s}] {new_k}`](#{new_s}.{new_k})"
            else:
                new = f"`[{new_s}] {new_k}` (provider)" if new_s not in cfg else f"`[{new_s}] {new_k}`"
            parts.append(f"| `[{old_s}] {old_k}` | {new} | {ver} |")
        parts.append("")

    for name, sec in cfg.items():
        parts.append(f"## [{name}]\n")
        desc = rst_to_md(sec.get("description") or "")
        if desc:
            parts.append(desc + "\n")
        for key, opt in (sec.get("options") or {}).items():
            opt = opt or {}
            parts.append(f'<a id="{name}.{key}"></a>\n\n### `{key}`\n')
            env = f"AIRFLOW__{name.upper()}__{key.upper()}"
            rows = [
                ("Default", code_cell(opt.get("default"))),
                ("Type", cell(opt.get("type"))),
                ("Environment variable", f"`{env}`"),
            ]
            if opt.get("example") not in (None, ""):
                rows.append(("Example", code_cell(opt.get("example"))))
            if opt.get("version_added"):
                rows.append(("Added in", cell(opt.get("version_added"))))
            if opt.get("sensitive"):
                rows.append(("Sensitive", f"yes: also `{env}_CMD` and `{env}_SECRET`; hidden in `airflow config list`"))
            if opt.get("version_deprecated"):
                reason = rst_to_md(opt.get("deprecation_reason") or "")
                rows.append(("Deprecated in", cell(f"{opt['version_deprecated']}. {reason}".strip())))
            old = deprecated.get((name, key))
            if old:
                rows.append(("Old name", f"`[{old[0]}] {old[1]}` (renamed in {old[2]})"))
            parts.append("| | |\n| :--- | :--- |")
            parts += [f"| {k} | {v} |" for k, v in rows]
            parts.append("")
            d = rst_to_md(opt.get("description") or "")
            if d:
                parts.append(d + "\n")
    return "\n".join(parts).rstrip() + "\n"


# --- CLI -----------------------------------------------------------------------------------


def usage(prefix: str, cmd: src.CliCommand) -> str:
    bits = [prefix]
    for a in cmd.args:
        if a.positional:
            name = a.metavar or a.flags[0]
            bits.append(f"[{name}]" if a.nargs in ("?", "*") else f"<{name}>")
    if any(not a.positional for a in cmd.args):
        bits.append("[options]")
    return " ".join(bits)


def arg_rows(cmd: src.CliCommand) -> list[str]:
    if not cmd.args:
        return ["No arguments.\n"]
    rows = ["| Argument | Description | Default |", "| :--- | :--- | :--- |"]
    for a in cmd.args:
        flags = ", ".join(f"`{f}`" for f in a.flags)
        if a.metavar and not a.positional and a.action not in ("store_true", "store_false"):
            flags += f" `{a.metavar}`"
        desc = rst_to_md(a.help).replace("\n", " ")
        if a.choices:
            desc += f" Choices: `{a.choices}`."
        if a.required:
            desc = "**Required.** " + desc
        if a.action in ("store_true", "store_false"):
            default = "flag"
        else:
            default = code_cell(a.default) if a.default is not None else ""
        rows.append(f"| {flags} | {cell(desc)} | {default} |")
    return rows + [""]


def gen_cli(checkout: str, origin: str) -> str:
    cmds = sorted(src.load_cli(checkout), key=lambda c: c.name)
    leaf = sum(len(c.subcommands) or 1 for c in cmds)
    intro = (
        f"Every core `airflow` command: {len(cmds)} top-level commands and groups, {leaf} commands in all. "
        "Most of them read the metadata database directly, so run them where the scheduler's configuration and "
        "database access are available, or use the REST API and `airflowctl` instead "
        "([REST API and airflowctl](05_rest_api_and_airflowctl.md)).\n\n"
        "Executors and auth managers from providers add more groups at run time, for example `airflow celery` "
        "(Celery provider), `airflow kubernetes` (cncf.kubernetes provider) and `airflow users` / `airflow roles` "
        "(FAB auth manager). Those come from the providers and are not listed here; run "
        "`airflow <group> --help` in your deployment.\n\n"
        "Every command also accepts `-h` / `--help`."
    )
    parts = [header("Airflow CLI Reference", src.CLI_CONFIG, origin, intro), "## Commands\n"]
    parts.append("| Command | Description |\n| :--- | :--- |")
    for c in cmds:
        parts.append(f"| [`airflow {c.name}`](#airflow-{c.name}) | {cell(c.help)} |")
    parts.append("")
    for c in cmds:
        parts.append(f"## airflow {c.name}\n")
        if c.help:
            parts.append(rst_to_md(c.help) + "\n")
        if c.subcommands:
            parts.append("| Subcommand | Description |\n| :--- | :--- |")
            for s in c.subcommands:
                parts.append(f"| [`{s.name}`](#airflow-{c.name}-{s.name}) | {cell(s.help)} |")
            parts.append("")
            for s in c.subcommands:
                parts.append(f"### airflow {c.name} {s.name}\n")
                text = rst_to_md(s.description or s.help)
                if text:
                    parts.append(text + "\n")
                parts.append(f"```text\n{usage(f'airflow {c.name} {s.name}', s)}\n```\n")
                parts += arg_rows(s)
        else:
            if c.description and c.description != c.help:
                parts.append(rst_to_md(c.description) + "\n")
            parts.append(f"```text\n{usage(f'airflow {c.name}', c)}\n```\n")
            parts += arg_rows(c)
    return "\n".join(parts).rstrip() + "\n"


# --- metrics -------------------------------------------------------------------------------


def gen_metrics(checkout: str, origin: str) -> str:
    metrics = src.load_metrics(checkout)
    by_type: dict[str, list[dict]] = {}
    for m in metrics:
        by_type.setdefault(m["type"], []).append(m)
    intro = (
        f"Every metric Airflow core emits: {len(metrics)} in all "
        + ", ".join(f"{len(v)} {k}s" for k, v in by_type.items())
        + ". Turn them on with `[metrics] statsd_on` or `[metrics] otel_on`, and see "
        "[Monitoring and Observability](../06_operations_and_housekeeping/03_monitoring_and_observability.md) "
        "for which ones to alert on.\n\n"
        "* **Name** is the metric name with tags (StatsD with Datadog tags, or OpenTelemetry attributes). "
        "Names are prefixed with `[metrics] statsd_prefix` / `otel_prefix` (default `airflow`).\n"
        "* **Legacy name** is the older form with the variables embedded in the name. It is emitted as well while "
        "`[metrics] legacy_names_on` is `True`; `-` means there is no legacy form.\n"
        "* `{placeholders}` are filled in at run time."
    )
    parts = [header("Metrics Reference", src.METRICS_YML, origin, intro)]
    titles = {"counter": "Counters", "gauge": "Gauges", "timer": "Timers"}
    for t, items in by_type.items():
        parts.append(f"## {titles.get(t, t.capitalize())}\n")
        parts.append("| Name | Legacy name | Description |\n| :--- | :--- | :--- |")
        for m in sorted(items, key=lambda m: m["name"]):
            legacy = m.get("legacy_name") or "-"
            legacy = "-" if legacy == "-" else f"`{legacy}`"
            parts.append(f"| `{m['name']}` | {legacy} | {cell(rst_to_md(m.get('description') or ''))} |")
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("checkout", help="path to an Apache Airflow source checkout (v3-4-stable)")
    ap.add_argument("--only", choices=("config", "cli", "metrics"))
    a = ap.parse_args()
    origin = src.describe_checkout(a.checkout)
    jobs = {
        "config": ("09_reference/01_airflow_cfg_reference.md", gen_config),
        "cli": ("09_reference/02_cli_reference.md", gen_cli),
        "metrics": ("09_reference/03_metrics_reference.md", gen_metrics),
    }
    for name, (path, fn) in jobs.items():
        if a.only and a.only != name:
            continue
        text = fn(a.checkout, origin)
        out = os.path.join(ROOT, path)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {path} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
